# The file parts, in order, with their (codes file, sentences file, L10n file); the first also
# holds ReasonParam. A code's sentences are an extension in their own file, so neither the enum
# nor either file passes SwiftLint's length limits.
PARTS = {
    "Reasons": ("ReasonCodes.swift", "ReasonSentences.swift", "L10n+Reasons.swift"),
    "Prose": ("ProseCodes.swift", "ProseSentences.swift", "L10n+Prose.swift"),
}
PARAM = re.compile(r"\{(\w+)\}")
# Longest line SwiftLint allows (it warns above this, and CI runs it strict).
LINE = 130


def camel(name):
    parts = name.lower().split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name):
    camel_name = camel(name)
    return camel_name[:1].upper() + camel_name[1:]


def params(text):
    """The values a sentence names, in order of first use."""
    return list(dict.fromkeys(PARAM.findall(text)))


def line_length_exemption(line):
    """The line, after a one-line SwiftLint exemption when it is longer than SwiftLint allows."""
    return ["      // swiftlint:disable:next line_length", line] if len(line) > LINE else [line]


def entries():
    """(enum, key, code, variant, names, english, russian, doc) for every sentence. A code with
    several shapes (api/reasons.py) has a sentence per shape, told apart by `variant`."""
    for enum, prefix, doc, items, _part in GROUPS:
        for code, en, ru, *rest in items:
            variant = rest[0] if rest else ""
            names = params(en)
            assert set(params(ru)) == set(names), code
            key = prefix + code + (f".{variant}" if variant else "")
            yield enum, key, code, variant, names, en, ru, f"{doc} {code} {variant}".rstrip()


# Value names that are Swift keywords, so their cases are written in backticks.
KEYWORDS = {"operator"}


def param_case(name):
    return f"`{camel(name)}`" if camel(name) in KEYWORDS else camel(name)


def swift_names(names):
    return ", ".join(f".{param_case(n)}" for n in names)


def l10n_name(enum, code, variant=""):
    return f"{enum[:1].lower()}{enum[1:]}{pascal(code)}{pascal(variant)}"


def in_part(enum, part):
    return any(e == enum and p == part for e, _x, _d, _i, p in GROUPS)


# Most lines of one generated file: SwiftLint's file_length limit (400) with room to spare.
FILE_LINES = 390


def l10n_files(part):
    """(file name, text) of a part's L10n entries: `L10n+<Part>.swift`, then `L10n+<Part>2.swift`
    and on when one file would pass SwiftLint's length limit."""
    head = [HEADER, "", "import Foundation", "", "extension L10n {"]
    files, out = [], list(head)
    for enum, key, code, variant, names, en, _ru, doc in entries():
        if not in_part(enum, part):
            continue
        entry = [
            f"  /// {doc}" + (f" (values: {', '.join(names)})" if names else ""),
            f"  static var {l10n_name(enum, code, variant)}: LocalizedStringResource {{",
            f'    LocalizedStringResource("{key}",',
            *line_length_exemption(f'      defaultValue: "{en}", bundle: bundle)'),
            "  }",
        ]
        if len(out) + len(entry) + 1 > FILE_LINES:
            files.append(out + ["}"])
            out = list(head)
        out += entry
    files.append(out + ["}"])
    stem = PARTS[part][2].removesuffix(".swift")
    return [(stem + (str(n + 1) if n else "") + ".swift", "\n".join(lines) + "\n")
            for n, lines in enumerate(files)]


def reason_swift(part):
    """(codes file text, sentences file text) of a part."""
    out = [HEADER, "", "import Foundation", ""]
    sentences = [HEADER, "", "import Foundation", ""]
    if part == next(iter(PARTS)):
        names = sorted({n for _e, _k, _c, _v, ns, *_ in entries() for n in ns})
        out += [
            "/// A value a reason sentence names (`params` of a gate, a fence or a cause).",
            "public enum ReasonParam: String, CaseIterable, Sendable {",
        ]
        for name in names:
            out.append(
                f"  case {param_case(name)}" + (f' = "{name}"' if camel(name) != name else "")
            )
        out += [
            "}",
            "",
        ]
    for enum, _prefix, doc, items, group_part in GROUPS:
        if group_part != part:
            continue
        out += [
            f"/// {doc} An unknown code has no case; show the bot's own text then.",
            f"public enum {enum}: String, CaseIterable, Sendable {{",
        ]
        codes = list(dict.fromkeys(code for code, *_ in items))
        for code in codes:
            out.append(f'  case {camel(code)} = "{code}"')
        out += ["}", ""]
        sentences += [
            f"extension {enum} {{",
            "  /// The code's sentences (one per shape the bot writes it in), each with the",
            "  /// values it names.",
            "  public var sentences: [ReasonSentence] {",
            "    switch self {",
        ]
        for code in codes:
            parts = [
                f"ReasonSentence(L10n.{l10n_name(enum, c, v)}, [{swift_names(ns)}])"
                for e, _k, c, v, ns, *_ in entries()
                if e == enum and c == code
            ]
            line = f"    case .{camel(code)}: [{', '.join(parts)}]"
            if len(line) > LINE:
                line = f"    case .{camel(code)}: [\n      " + ",\n      ".join(parts) + ",\n    ]"
            sentences.append(line)
        sentences += [
            "    }",
            "  }",
            "",
            "  /// The first sentence whose values the bot all sent, filled in; nil when none",
            "  /// fits.",
            "  public func text(_ params: [String: String]) -> String? {",
            "    sentences.lazy.compactMap { $0.text(params) }.first",
            "  }",
            "}",
            "",
        ]
    return ("\n".join(out).rstrip() + "\n", "\n".join(sentences).rstrip() + "\n")


def catalog_entry(en, ru, names, doc):
    return {
        "comment": doc,
        "extractionState": "manual",
        "localizations": {
            "en": {"stringUnit": {"state": "translated", "value": en}},
            "ru": {"stringUnit": {"state": "translated", "value": ru}},
        },
    }


def codes(enum):
    """The codes of one group, with the values each of its sentences names."""
    found = {}
    for e, _k, code, _v, ns, *_ in entries():
        if e == enum:
            found.setdefault(code, []).append(set(ns))
    return found


def check():
    """Differences between the committed files and this list; empty when they agree."""
    problems = []
    for part, (codes_file, sentences_file, l10n_file) in PARTS.items():
        codes_text, sentences_text = reason_swift(part)
        generated = [(codes_file, codes_text), (sentences_file, sentences_text), *l10n_files(part)]
        for name, text in generated:
            path = KIT / name
            if not path.exists() or path.read_text() != text:
                problems.append(f"{name} differs from the generator")
        stem = l10n_file.removesuffix(".swift")
        made = {name for name, _ in l10n_files(part)}
        for path in KIT.glob(stem + "*.swift"):
            number = path.name.removeprefix(stem).removesuffix(".swift")
            if path.name not in made and number.isdigit():
                problems.append(f"{path.name} is no longer generated")
    strings = json.loads((KIT / "Resources/Localizable.xcstrings").read_text())["strings"]
    for _enum, key, _code, _variant, names, en, ru, doc in entries():
        if strings.get(key) != catalog_entry(en, ru, names, doc):
            problems.append(f"catalog entry {key} differs from the generator")
    return problems


def write():
    for part, (codes_file, sentences_file, l10n_file) in PARTS.items():
        codes_text, sentences_text = reason_swift(part)
        (KIT / codes_file).write_text(codes_text)
        (KIT / sentences_file).write_text(sentences_text)
        stem = l10n_file.removesuffix(".swift")
        for path in KIT.glob(stem + "*.swift"):
            if path.name.removeprefix(stem).removesuffix(".swift").isdigit():
                path.unlink()
        for name, text in l10n_files(part):
            (KIT / name).write_text(text)
    path = KIT / "Resources/Localizable.xcstrings"
    catalog = json.loads(path.read_text())
    for _enum, key, _code, _variant, names, en, ru, doc in entries():
        catalog["strings"][key] = catalog_entry(en, ru, names, doc)
    catalog["strings"] = dict(sorted(catalog["strings"].items()))
    path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        found = check()
        print("\n".join(found) or "reason sentences up to date")
        sys.exit(1 if found else 0)
    write()
